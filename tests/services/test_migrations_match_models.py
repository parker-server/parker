from pathlib import Path

from alembic import command
from alembic.config import Config

from app.config import settings

ALEMBIC_DIR = Path(__file__).resolve().parents[2] / "alembic"


def test_alembic_check_finds_no_drift_on_a_freshly_migrated_database(tmp_path, monkeypatch):
    """Models and migrations must describe the same schema.

    If this fails, a model and its migration disagree. Fix the model, or add a
    migration for the change, until `alembic check` is clean.
    """
    monkeypatch.setattr(settings, "database_url", f"sqlite:///{(tmp_path / 'comics.db').as_posix()}")
    # No ini file, so env.py leaves test logging alone.
    config = Config()
    config.set_main_option("script_location", str(ALEMBIC_DIR))

    command.upgrade(config, "head")

    # Raises AutogenerateDiffsDetected listing each difference. The comics_fts tables
    # exist at head but have no model, so this also covers env.py's include_name filter.
    command.check(config)
